CREATE TABLE IF NOT EXISTS TM_IMPORTED_PROJECTS (
    ID NUMBER(10) PRIMARY KEY,
    NAME NVARCHAR2(100) NOT NULL,
    DESCRIPTION NCLOB,
    PARENT_ID NUMBER(10),
    IS_PUBLIC NUMBER(1) NOT NULL,
    STATE VARCHAR2(10) NOT NULL,
    REVISION NUMBER(10) NOT NULL,
    ISSUES_ENABLED NUMBER(1) NOT NULL,
    TIME_ENABLED NUMBER(1) NOT NULL,
    INHERIT_PARENT_ROLES NUMBER(1) NOT NULL,
    FOREIGN KEY (PARENT_ID) REFERENCES TM_IMPORTED_PROJECTS(ID) DEFERRABLE INITIALLY DEFERRED
)
