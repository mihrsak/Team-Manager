CREATE TABLE IF NOT EXISTS TM_OVERVIEW_TASKS (
    ID NUMBER(9) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE NVARCHAR2(200) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'new' NOT NULL,
    REVISION NUMBER(9) DEFAULT 1 NOT NULL,
    CONSTRAINT TM_OVERVIEW_TITLE_UQ UNIQUE (TITLE),
    CONSTRAINT TM_OVERVIEW_STATUS_CK CHECK (STATUS IN ('new','active','done'))
)
