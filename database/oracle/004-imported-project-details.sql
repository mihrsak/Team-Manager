CREATE TABLE IF NOT EXISTS TM_IMPORTED_PROJECT_MEMBERS (
    PROJECT_ID NUMBER(10) NOT NULL REFERENCES TM_IMPORTED_PROJECTS(ID),
    USER_ID NUMBER(10) NOT NULL,
    ROLE_NAME NVARCHAR2(30) NOT NULL,
    PRIMARY KEY (PROJECT_ID, USER_ID)
);
CREATE TABLE IF NOT EXISTS TM_IMPORTED_PROJECT_ROLES (
    PROJECT_ID NUMBER(10) NOT NULL,
    USER_ID NUMBER(10) NOT NULL,
    ROLE_NAME NVARCHAR2(30) NOT NULL,
    PRIMARY KEY (PROJECT_ID, USER_ID, ROLE_NAME),
    FOREIGN KEY (PROJECT_ID, USER_ID) REFERENCES TM_IMPORTED_PROJECT_MEMBERS(PROJECT_ID, USER_ID)
);
CREATE TABLE IF NOT EXISTS TM_IMPORTED_MILESTONES (
    ID NUMBER(10) PRIMARY KEY,
    PROJECT_ID NUMBER(10) NOT NULL REFERENCES TM_IMPORTED_PROJECTS(ID),
    KIND VARCHAR2(12) NOT NULL,
    NAME NVARCHAR2(100) NOT NULL,
    DESCRIPTION NCLOB,
    TARGET_DATE DATE,
    IS_COMPLETE NUMBER(1) NOT NULL,
    REVISION NUMBER(10) NOT NULL
);
CREATE TABLE IF NOT EXISTS TM_IMPORTED_ISSUE_LINKS (
    SOURCE_ID NUMBER(10) NOT NULL REFERENCES TM_IMPORTED_ISSUES(ID),
    TARGET_ID NUMBER(10) NOT NULL REFERENCES TM_IMPORTED_ISSUES(ID),
    KIND VARCHAR2(12) NOT NULL,
    PRIMARY KEY (SOURCE_ID, TARGET_ID, KIND)
);
CREATE TABLE IF NOT EXISTS TM_IMPORTED_ISSUE_EVENTS (
    ID NUMBER(10) PRIMARY KEY,
    ISSUE_ID NUMBER(10) NOT NULL REFERENCES TM_IMPORTED_ISSUES(ID),
    USER_ID NUMBER(10) NOT NULL,
    KIND VARCHAR2(20) NOT NULL,
    BODY NCLOB,
    CREATED_AT TIMESTAMP(7) NOT NULL
);
CREATE TABLE IF NOT EXISTS TM_IMPORTED_TIME_ENTRIES (
    ID NUMBER(10) PRIMARY KEY,
    ISSUE_ID NUMBER(10) NOT NULL REFERENCES TM_IMPORTED_ISSUES(ID),
    USER_ID NUMBER(10) NOT NULL,
    WORK_DATE DATE NOT NULL,
    HOURS NUMBER(6,2) NOT NULL,
    NOTE NVARCHAR2(1000),
    CREATED_AT TIMESTAMP(7) NOT NULL,
    ACTIVITY NVARCHAR2(60) NOT NULL
)
