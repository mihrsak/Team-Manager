CREATE TABLE IF NOT EXISTS TM_IMPORTED_ISSUES (
    ID NUMBER(10) PRIMARY KEY,
    PROJECT_ID NUMBER(10) NOT NULL REFERENCES TM_IMPORTED_PROJECTS(ID),
    TITLE NVARCHAR2(200) NOT NULL,
    DESCRIPTION NCLOB,
    ISSUE_TYPE NVARCHAR2(50) NOT NULL,
    PRIORITY NVARCHAR2(20) NOT NULL,
    STATUS NVARCHAR2(30) NOT NULL,
    ASSIGNEE_ID NUMBER(10),
    DUE_DATE DATE,
    CREATED_BY NUMBER(10) NOT NULL,
    CREATED_AT TIMESTAMP(7) NOT NULL,
    REVISION NUMBER(10) NOT NULL,
    START_DATE DATE,
    ROADMAP_ITEM_ID NUMBER(10),
    IS_PRIVATE NUMBER(1) NOT NULL
)
