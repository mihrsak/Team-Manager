// Regenerate after updating the reviewed schema manifest; no database access is needed.
const fs = require('node:fs');
const schema = JSON.parse(fs.readFileSync('database/oracle/relational-schema.json', 'utf8'));
const q = name => '"' + name.replaceAll('"', '""') + '"';
const table = name => q('TMR_' + name);
const expression = sql => sql.replace(/\[([^\]]+)\]/g, (_, name) => q(name));
function type(c) {
    switch(c.type) {
        case 'int': return 'NUMBER(10)';
        case 'bigint': return 'NUMBER(19)';
        case 'bit': return 'NUMBER(1)';
        case 'decimal': return `NUMBER(${c.precision},${c.scale})`;
        case 'date': return 'DATE';
        case 'datetime2': return 'TIMESTAMP(7)';
        case 'binary': return `RAW(${c.length})`;
        case 'varbinary': return 'BLOB';
        case 'uniqueidentifier': return 'VARCHAR2(36 CHAR)';
        case 'nvarchar': return c.length < 0 || c.length > 4000 ? 'NCLOB' : `NVARCHAR2(${c.length / 2})`;
        case 'varchar': return `VARCHAR2(${c.length} CHAR)`;
        default: throw Error('Unmapped type: ' + c.type);
    }
}
const statements = [
    'CREATE TABLE IF NOT EXISTS TMR_WORKSPACE (ID NUMBER(1) PRIMARY KEY CHECK (ID=1), SCHEMA_VERSION NUMBER(4) NOT NULL, REVISION NUMBER(18) NOT NULL, SOURCE_REVISION NUMBER(18) NOT NULL, MIGRATED_AT TIMESTAMP(7) NOT NULL)',
    'CREATE TABLE IF NOT EXISTS TMR_COUNTERS (TABLE_NAME VARCHAR2(128) PRIMARY KEY, LAST_VALUE NUMBER(19) NOT NULL CHECK (LAST_VALUE>=0))'
];
for (const t of schema.tables) {
    if(t.columns.length > 60) throw Error('Empty-string mask requires at most 60 columns');
    const columns = ['"__EMPTY" NUMBER(19) DEFAULT 0 NOT NULL CHECK ("__EMPTY">=0)'];
    for(const [i,c] of t.columns.entries()) {
        const isText = ['varchar','nvarchar'].includes(c.type);
        columns.push(`${q(c.name)} ${type(c)}${!c.nullable && !isText ? ' NOT NULL' : ''}`);
        if(!c.nullable && isText) columns.push(`CHECK (${q(c.name)} IS NOT NULL OR BITAND("__EMPTY",${2**i})<>0)`);
        if(c.type==='bit') columns.push(`CHECK (${q(c.name)} IN (0,1))`);
    }
    for(const k of t.keys.filter(k=>!k.filter)) columns.push(`CONSTRAINT ${q(k.name)} ${k.primary?'PRIMARY KEY':'UNIQUE'} (${k.columns.map(q).join(',')}) DEFERRABLE INITIALLY DEFERRED`);
    for(const check of t.checks.filter(c=>!c.includes('datalength'))) columns.push('CHECK '+expression(check));
    statements.push(`CREATE TABLE IF NOT EXISTS ${table(t.name)} (\n    ${columns.join(',\n    ')}\n)`);
}
for(const t of schema.tables) {
    for(const k of t.foreignKeys) statements.push(`ALTER TABLE ${table(t.name)} ADD CONSTRAINT ${q(k.name)} FOREIGN KEY (${k.columns.map(q).join(',')}) REFERENCES ${table(k.referencedTable)} (${k.referencedColumns.map(q).join(',')}) DEFERRABLE INITIALLY DEFERRED`);
    for(const k of t.keys.filter(k=>k.filter)) statements.push(`CREATE UNIQUE INDEX IF NOT EXISTS ${q(k.name)} ON ${table(t.name)} (${k.columns.map(c=>`CASE WHEN ${expression(k.filter)} THEN ${q(c)} END`).join(',')})`);
    for(const [i,k] of t.foreignKeys.entries()) {
        if(!t.keys.some(key=>!key.filter && k.columns.every((c,j)=>c===key.columns[j])))
            statements.push(`CREATE INDEX IF NOT EXISTS ${q(`TMR_I_${t.name}_${i}`)} ON ${table(t.name)} (${k.columns.map(q).join(',')})`);
    }
    if(t.checks.some(c=>c.includes('datalength'))) statements.push(`CREATE OR REPLACE TRIGGER ${q('TMR_SIZE_'+t.name)} BEFORE INSERT OR UPDATE ON ${table(t.name)} FOR EACH ROW\nBEGIN\n    IF DBMS_LOB.GETLENGTH(:NEW."Content") NOT BETWEEN 1 AND 10485760 THEN\n        RAISE_APPLICATION_ERROR(-20002,'Attachment must contain between 1 and 10485760 bytes.');\n    END IF;\nEND;`);
}
// Install before copying data: old application binaries must not edit the archived JSON afterwards.
statements.push(`CREATE OR REPLACE TRIGGER TM_ACTIVE_WORKSPACE_FROZEN BEFORE INSERT OR UPDATE OR DELETE ON TM_ACTIVE_WORKSPACE\nDECLARE active_rows NUMBER;\nBEGIN\n    SELECT COUNT(*) INTO active_rows FROM TMR_WORKSPACE WHERE ID=1;\n    IF active_rows>0 THEN\n        RAISE_APPLICATION_ERROR(-20001,'Workspace migrated to relational Oracle tables; legacy JSON is archived.');\n    END IF;\nEND;`);
fs.writeFileSync('database/oracle/006-relational-workspace.sql', '-- Generated by scripts/Generate-OracleRelational.cjs. Slash separates executable commands.\n'+statements.join('\n/\n')+'\n/\n');
console.log('Generated relational schema for '+schema.tables.length+' tables.');
